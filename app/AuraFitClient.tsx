interface CompressedPhotoResult {
  blob: Blob;
  dataUrl: string;
  ext: 'webp' | 'jpg';
  mimeType: string;
  originalBytes: number;
  compressedBytes: number;
}

const compressImageToWebP = (
  file: File,
  maxDimension = 1280,
  quality = 0.84
): Promise<CompressedPhotoResult> => {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = () => reject(new Error('파일을 읽을 수 없습니다.'));
    reader.onload = (ev) => {
      const rawDataUrl = typeof ev.target?.result === 'string' ? ev.target.result : '';
      if (!rawDataUrl) {
        reject(new Error('이미지 데이터가 비어 있습니다.'));
        return;
      }
      const img = new window.Image();
      img.onload = () => {
        try {
          let targetW = img.naturalWidth || img.width || 800;
          let targetH = img.naturalHeight || img.height || 800;
          if (targetW > maxDimension || targetH > maxDimension) {
            if (targetW >= targetH) {
              targetH = Math.round((targetH * maxDimension) / targetW);
              targetW = maxDimension;
            } else {
              targetW = Math.round((targetW * maxDimension) / targetH);
              targetH = maxDimension;
            }
          }
          const canvas = document.createElement('canvas');
          canvas.width = targetW;
          canvas.height = targetH;
          const ctx = canvas.getContext('2d');
          if (!ctx) {
            resolve({
              blob: file,
              dataUrl: rawDataUrl,
              ext: 'jpg',
              mimeType: file.type || 'image/jpeg',
              originalBytes: file.size,
              compressedBytes: file.size,
            });
            return;
          }
          ctx.drawImage(img, 0, 0, targetW, targetH);

          canvas.toBlob(
            (webpBlob) => {
              const finalizeBlob = (b: Blob, ext: 'webp' | 'jpg', mime: string) => {
                const bReader = new FileReader();
                bReader.onload = () => {
                  resolve({
                    blob: b,
                    dataUrl: typeof bReader.result === 'string' ? bReader.result : rawDataUrl,
                    ext,
                    mimeType: mime,
                    originalBytes: file.size,
                    compressedBytes: b.size,
                  });
                };
                bReader.onerror = () => {
                  resolve({
                    blob: b,
                    dataUrl: rawDataUrl,
                    ext,
                    mimeType: mime,
                    originalBytes: file.size,
                    compressedBytes: b.size,
                  });
                };
                bReader.readAsDataURL(b);
              };

              if (webpBlob && webpBlob.type === 'image/webp') {
                finalizeBlob(webpBlob, 'webp', 'image/webp');
              } else {
                canvas.toBlob(
                  (jpgBlob) => {
                    if (jpgBlob) {
                      finalizeBlob(jpgBlob, 'jpg', 'image/jpeg');
                    } else {
                      resolve({
                        blob: file,
                        dataUrl: rawDataUrl,
                        ext: 'jpg',
                        mimeType: file.type || 'image/jpeg',
                        originalBytes: file.size,
                        compressedBytes: file.size,
                      });
                    }
                  },
                  'image/jpeg',
                  quality
                );
              }
            },
            'image/webp',
            quality
          );
        } catch {
          resolve({
            blob: file,
            dataUrl: rawDataUrl,
            ext: 'jpg',
            mimeType: file.type || 'image/jpeg',
            originalBytes: file.size,
            compressedBytes: file.size,
          });
        }
      };
      img.onerror = () => {
        resolve({
          blob: file,
          dataUrl: rawDataUrl,
          ext: 'jpg',
          mimeType: file.type || 'image/jpeg',
          originalBytes: file.size,
          compressedBytes: file.size,
        });
      };
      img.src = rawDataUrl;
    };
    reader.readAsDataURL(file);
  });
};

const createSvgItem = (
  bgColor: string,
  iconEmoji: string,
  label: string,
  subLabel = ''
): string => {
  const isDarkBg = ['#18181B', '#27272A', '#3F3F46'].includes(
    bgColor.toUpperCase()
  );
  const titleFill = isDarkBg ? '#F4F4F5' : '#27272A';
  const subFill = isDarkBg ? '#A1A1AA' : '#71717A';
  const circleOpacity = isDarkBg ? '0.12' : '0.45';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="450" viewBox="0 0 400 450">
    <rect width="400" height="450" rx="24" fill="${bgColor}"/>
    <circle cx="200" cy="195" r="105" fill="#ffffff" fill-opacity="${circleOpacity}"/>
    <text x="50%" y="45%" dominant-baseline="middle" text-anchor="middle" font-size="112">${iconEmoji}</text>
    <text x="50%" y="76%" dominant-baseline="middle" text-anchor="middle" font-family="sans-serif" font-size="20" font-weight="bold" fill="${titleFill}">${label}</text>
    <text x="50%" y="83%" dominant-baseline="middle" text-anchor="middle" font-family="sans-serif" font-size="13" font-weight="600" fill="${subFill}">${subLabel}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
};

