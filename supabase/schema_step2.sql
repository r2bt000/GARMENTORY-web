-- 1. 유저 오픈 옷장 프로필 테이블 (auth.users 와 1:1 연동)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  handle text not null,
  badge text not null default '오픈 옷장 멤버',
  dna text[] not null default array['Editorial Minimal', 'Daily Archive'],
  style_request text not null default '제 옷장 아이템들을 터치해서 어울리는 코디를 자유롭게 제안해 주세요!',
  is_public boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. 내 옷장 아이템 테이블 (유저별 소유권 분리)
create table if not exists public.wardrobe_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  category text not null check (category in ('아우터', '상의', '하의', '신발', '악세사리')),
  season text not null default '사계절',
  status text not null default '보유 중' check (status in ('보유 중', '구매 예정')),
  source_url text default '',
  image_url text not null,
  created_at timestamptz not null default now()
);

-- 3. 저장된 코디 룩북 테이블 (본인 전용 아카이브)
create table if not exists public.saved_looks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  genre text not null,
  mode text not null check (mode in ('DAY', 'NIGHT')),
  title text not null,
  items_json jsonb not null default '[]'::jsonb,
  note text not null default '',
  created_at timestamptz not null default now()
);

-- 4. 커뮤니티 오픈 옷장 코디 제안함 테이블
create table if not exists public.outfit_proposals (
  id uuid primary key default gen_random_uuid(),
  target_user_id uuid not null references auth.users(id) on delete cascade,
  proposer_user_id uuid references auth.users(id) on delete set null,
  proposer_handle text not null,
  note text not null,
  item_ids bigint[] not null default '{}',
  items_snapshot jsonb not null default '[]'::jsonb,
  likes integer not null default 1,
  created_at timestamptz not null default now()
);

-- 성능 최적화 인덱스
create index if not exists idx_wardrobe_user_id on public.wardrobe_items(user_id);
create index if not exists idx_saved_looks_user_id on public.saved_looks(user_id);
create index if not exists idx_proposals_target_user on public.outfit_proposals(target_user_id);

-- =====================================================================
-- 5. 회원가입 즉시 기본 프로필 자동 생성 트리거
-- =====================================================================
create or replace function public.handle_new_aurafit_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
declare
  raw_name text;
  clean_handle text;
begin
  raw_name := coalesce(
    new.raw_user_meta_data ->> 'preferred_username',
    new.raw_user_meta_data ->> 'name',
    split_part(coalesce(new.email, 'user'), '@', 1)
  );
  clean_handle := '@' || regexp_replace(lower(raw_name), '[^a-z0-9가-힣_]', '', 'g');
  if length(clean_handle) < 3 then
    clean_handle := '@aurafit_' || substr(new.id::text, 1, 6);
  end if;

  insert into public.profiles (id, handle)
  values (new.id, clean_handle)
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_aurafit_user();

-- =====================================================================
-- 6. Row Level Security (RLS) 철통 권한 정책 활성화
-- =====================================================================
alter table public.profiles enable row level security;
alter table public.wardrobe_items enable row level security;
alter table public.saved_looks enable row level security;
alter table public.outfit_proposals enable row level security;

-- 기존 정책 충돌 방지용 초기화
drop policy if exists "Public profiles are viewable by everyone" on public.profiles;
drop policy if exists "Users can insert own profile" on public.profiles;
drop policy if exists "Users can update own profile" on public.profiles;

drop policy if exists "Wardrobe viewable if owner or public profile" on public.wardrobe_items;
drop policy if exists "Users can insert own wardrobe items" on public.wardrobe_items;
drop policy if exists "Users can update own wardrobe items" on public.wardrobe_items;
drop policy if exists "Users can delete own wardrobe items" on public.wardrobe_items;

drop policy if exists "Users can view own saved looks" on public.saved_looks;
drop policy if exists "Users can insert own saved looks" on public.saved_looks;
drop policy if exists "Users can delete own saved looks" on public.saved_looks;

drop policy if exists "Proposals viewable by everyone" on public.outfit_proposals;
drop policy if exists "Authenticated users can send proposals" on public.outfit_proposals;
drop policy if exists "Authenticated users can update proposal likes" on public.outfit_proposals;
drop policy if exists "Target user or proposer can delete proposal" on public.outfit_proposals;

-- [profiles 정책] 오픈 프로필은 누구나 조회 가능, 생성·수정은 본인만 가능
create policy "Public profiles are viewable by everyone"
  on public.profiles for select
  using (is_public = true or auth.uid() = id);

create policy "Users can insert own profile"
  on public.profiles for insert
  with check (auth.uid() = id);

create policy "Users can update own profile"
  on public.profiles for update
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- [wardrobe_items 정책] 본인 옷장이거나 오픈 옷장(is_public=true)인 경우 조회 허용, 추가·수정·삭제는 오직 본인만 가능
create policy "Wardrobe viewable if owner or public profile"
  on public.wardrobe_items for select
  using (
    auth.uid() = user_id
    or exists (
      select 1 from public.profiles p
      where p.id = wardrobe_items.user_id and p.is_public = true
    )
  );

create policy "Users can insert own wardrobe items"
  on public.wardrobe_items for insert
  with check (auth.uid() = user_id);

create policy "Users can update own wardrobe items"
  on public.wardrobe_items for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "Users can delete own wardrobe items"
  on public.wardrobe_items for delete
  using (auth.uid() = user_id);

-- [saved_looks 정책] 저장된 룩북은 본인만 조회·추가·삭제 가능
create policy "Users can view own saved looks"
  on public.saved_looks for select
  using (auth.uid() = user_id);

create policy "Users can insert own saved looks"
  on public.saved_looks for insert
  with check (auth.uid() = user_id);

create policy "Users can delete own saved looks"
  on public.saved_looks for delete
  using (auth.uid() = user_id);

-- [outfit_proposals 정책] 오픈 옷장 코디 제안 조회 및 로그인 유저의 제안 등록 허용, 삭제는 옷장 주인 또는 작성자만 가능
create policy "Proposals viewable by everyone"
  on public.outfit_proposals for select
  using (true);

create policy "Authenticated users can send proposals"
  on public.outfit_proposals for insert
  with check (auth.role() = 'authenticated');

create policy "Authenticated users can update proposal likes"
  on public.outfit_proposals for update
  using (auth.role() = 'authenticated');

create policy "Target user or proposer can delete proposal"
  on public.outfit_proposals for delete
  using (auth.uid() = target_user_id or auth.uid() = proposer_user_id);
